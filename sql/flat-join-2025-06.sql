-- =====================================================================
--  A-9 (নবনীতা বিশ্বাস) ও C-9 (ছবি রাণী শীল) — সার্ভিস চার্জ জুন-২০২৫ থেকে
--  ---------------------------------------------------------------------
--  এই দুই ফ্ল্যাটের চার্জ ধার্য হয়েছে জুন-২০২৫ থেকে, আগস্ট-২৪ থেকে নয়।
--  join_month বসালে সফটওয়্যার (flatStartMonth) ঐ মাস থেকে চার্জ ধরে —
--  তার আগের মাসে বকেয়া দেখায় না, একক ফ্ল্যাট এন্ট্রি ও রিপোর্টে ঐ
--  মাসগুলো "প্রযোজ্য নয়" হয়। বাকি সব ফ্ল্যাট অপরিবর্তিত।
--
--  যাচাই (১২-১০-২০২৬): দুটিতেই join_month খালি; জুন-২৫ এর আগে কোনো
--  জমা নেই (A-9: কোনো জমা নেই, C-9: এপ্রিল-২৬ থেকে), তাই অগ্রীম তৈরি হবে না।
--
--  বিকল্প: UI থেকেও করা যায় — ফ্ল্যাট ব্যবস্থাপনা → সম্পাদনা →
--  "চার্জ গণনা শুরুর মাস" = ২০২৫-০৬।
-- =====================================================================

-- ধাপ ১ — আগে দেখুন
SELECT id, serial, flat_no, owner_name, join_month
FROM flats WHERE flat_no IN ('A-9', 'C-9') ORDER BY serial;

-- ধাপ ২ — যোগদানের মাস বসান (join_month খালি থাকলে তবেই)
UPDATE flats SET join_month = '2025-06'
WHERE flat_no IN ('A-9', 'C-9') AND join_month IS NULL;

-- ধাপ ৩ — মিলিয়ে দেখুন (দুই সারিতেই 2025-06 আসবে)
SELECT id, serial, flat_no, owner_name, join_month
FROM flats WHERE flat_no IN ('A-9', 'C-9') ORDER BY serial;
