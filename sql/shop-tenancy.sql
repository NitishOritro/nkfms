-- =====================================================================
--  দোকানের ভাড়াটিয়ার ইতিহাস (tenancies) — কে, কোন মাস থেকে কোন মাস,
--  কত ভাড়া, কত অ্যাডভান্স; মাঝের মাসগুলো = দোকান ফাঁকা (বকেয়া নয়)
--  ---------------------------------------------------------------------
--  আগে দোকানে একটাই সময়কাল ছিল (join_month → closed_from) ও একটাই নাম।
--  দোকান ফাঁকা থেকে আবার ভাড়া হলে সেটি ধরা যেত না — ফাঁকা মাসগুলোতেও
--  বকেয়া দেখাত। এখন shops.tenancies (jsonb) — একটি তালিকা:
--    [{ "id": "t-…", "tenantName": "…", "phone": "…",
--       "fromMonth": "2025-07", "toMonth": "2026-02",   -- toMonth "" = চলছে
--       "rent": 2500,            -- ০/খালি হলে দোকানের সাধারণ হার
--       "advanceAmount": 50000, "advanceAdjust": 1000, "note": "…" }]
--  নিয়ম:
--    • tenancies থাকলে কেবল ঐ সময়কালের মাসগুলোতেই ভাড়া ধার্য; বাকি মাস
--      "ফাঁকা" — ছকে খালি ঘর, বকেয়ার হিসাবে নেই।
--    • tenancies খালি থাকলে আগের নিয়মই (join_month / closed_from / tenant_name)।
--    • অ্যাডভান্সের সারি (advance / advance-adjust / advance-refund) যে মাসের,
--      সেই মাস যে ভাড়াটিয়ার সময়কালে পড়ে তাঁর খাতায়; সময়কালের বাইরে
--      (যেমন ছাড়ার পরের মাসে ফেরত) হলে তার আগের সর্বশেষ ভাড়াটিয়ার।
--
--  Supabase SQL Editor-এ চালান। একাধিকবার চালালেও ক্ষতি নেই।
-- =====================================================================

ALTER TABLE shops ADD COLUMN IF NOT EXISTS tenancies jsonb;

-- অ্যাডভান্সের সারি কোন ভাড়াটিয়ার — ফর্ম থেকে লেখা হলে এখানে id বসে; খালি
-- থাকলে মাস দেখে ঠিক করা হয় (উপরের নিয়ম)। ভাড়া/বিদ্যুতের সারিতে ঐচ্ছিক।
ALTER TABLE shop_rents ADD COLUMN IF NOT EXISTS tenancy_id text;

-- মিলিয়ে দেখুন
SELECT shop_no, tenant_name, join_month, closed_from, tenancies
FROM shops ORDER BY serial;
